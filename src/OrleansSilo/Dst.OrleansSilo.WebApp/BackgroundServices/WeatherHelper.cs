    public static readonly DateOnly[] Days = Enumerable.Range(1, 365)
        .Select(day => new DateOnly(DateTime.UtcNow.Year, 1, 1).AddDays(day - 1))
        .ToArray();

    public static IReadOnlyCollection<(DateOnly Day, string Location)> GetCombinations()
    {
        return Locations
            .SelectMany(location => Days
                .Select(day => (Day: day, Location: location)))
            .OrderBy(x => x.Day)
            .ToArray();
    }
